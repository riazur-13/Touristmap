// The distinct categories present in the data, in first-seen order. Used to
// build the filter chips — keep this as the single source of that list so the
// chips can never drift from the data.
export const getAllCategories = () => [
  ...new Set(attractions.map((attr) => attr.category)),
];

// [[south, west], [north, east]] around the given attractions, in the shape
// Leaflet accepts for `bounds` / `fitBounds`.
export const getBounds = (list) => {
  const lats = list.map((a) => a.coordinates[0]);
  const lngs = list.map((a) => a.coordinates[1]);
  return [
    [Math.min(...lats), Math.min(...lngs)],
    [Math.max(...lats), Math.max(...lngs)],
  ];
};

// Slugs are stored on each attraction (they are public URLs, so they must not
// change when a name is edited). Uniqueness is enforced by attractions.test.js.
const BY_SLUG = new Map(attractions.map((a) => [a.slug, a]));

export const findBySlug = (slug) => BY_SLUG.get(slug) ?? null;

export default attractions;
